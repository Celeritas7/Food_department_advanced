// Component interaction checks without a browser or production connection.
import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
const { default: ScaleControl } = await server.ssrLoadModule('/src/components/forms/RecipeScaleControl.jsx');
const { default: CookDialog } = await server.ssrLoadModule('/src/components/forms/CookDialog.jsx');
const { default: RecipePage } = await server.ssrLoadModule('/src/components/pages/RecipePage.jsx');
const ingredients = [{ id: 'c', name: 'Cabbage', unit: 'g', stock_qty: 500 }];
const links = [{ dish_id: 'd', ingredient_id: 'c', qty: 800, recipe_unit: 'g' }];
const dish = { id: 'd', name: 'Kimchi', status: 'In Progress', recipe_data: { batchScale: 1, ingredientGroups: [{ id: 'g', name: 'Main', items: [{ id: 'i', text: 'Cabbage', ingredientId: 'c' }] }], preparation: [], cookingSteps: [] } };
let tree;
const button = name => tree.root.findAllByType('button').find(b => b.children.join('') === name);
const input = name => tree.root.findByProps({ 'aria-label': name });
const change = (name, value) => act(() => input(name).props.onChange({ target: { value } }));
const click = async name => { const b = button(name); assert.ok(b, `Missing button ${name}`); await act(async () => { await b.props.onClick(); }); };
try {
 const calls = [];
 act(() => { tree = TestRenderer.create(React.createElement(ScaleControl, { dish, links, ingredients, onApply: async (...args) => calls.push(args) })); });
 await click('Half'); assert.equal(calls.at(-1)[0], 0.5);
 change('Batch multiplier','0'); await click('Apply batch');
 assert.equal(calls.length, 1); assert.match(tree.root.findByProps({role:'alert'}).children.join(''), /greater than 0/);
 change('Scale ingredient','c'); change('Target ingredient amount','400'); await click('Scale to amount');
 assert.equal(calls.at(-1)[0], 0.5);
 change('Original servings','4'); change('Wanted servings','2'); await click('Scale servings');
 assert.deepEqual(calls.at(-1), [0.5, {baseServings:4}]);
 act(() => tree.unmount());
 act(() => { tree = TestRenderer.create(React.createElement(ScaleControl, { dish, links, ingredients, onApply: async () => { throw new Error('Save failed'); } })); });
 await click('Double'); assert.match(tree.root.findByProps({role:'alert'}).children.join(''), /Save failed/);
 assert.equal(tree.root.findAllByType('fieldset')[0].props.disabled, false);
 act(() => tree.unmount());
 const deductions = [];
 act(() => { tree = TestRenderer.create(React.createElement(CookDialog, { dish: {...dish,recipe_data:{batchScale:0.5}}, recipeIngs: links, recipeInts: [], ingredients, intermediates: [], onCancel:()=>{}, onConfirm:async rows=>deductions.push(rows) })); });
 assert.equal(tree.root.findByProps({'aria-label':'Quantity for Cabbage'}).props.value,'400');
 await click('Confirm cook'); assert.deepEqual(deductions[0],[{ingredient_id:'c',qty:400,unit:'g'}]);
 act(() => tree.root.findByProps({'aria-label':'Quantity for Cabbage'}).props.onChange({target:{value:'501'}}));
 assert.equal(button('Confirm cook').props.disabled,true);
 act(() => tree.unmount());
 const saved = [], updatedLinks = [];
 act(() => { tree = TestRenderer.create(React.createElement(RecipePage, { dish, ingredients, dishIngs:links, onSave:async(id,data)=>saved.push({id,data}), onUpdateDishLink:(...args)=>updatedLinks.push(args), notify:()=>{}, onBack:()=>{} })); });
 await click('Half'); assert.equal(saved.at(-1).data.batchScale,0.5);
 assert.equal(links[0].qty,800); assert.deepEqual(updatedLinks,[]);
 const amountPill = tree.root.findAllByType('button').find(b => b.props.title === 'Select Original batch to edit recipe quantities');
 assert.ok(amountPill); assert.equal(amountPill.props.disabled,true);
 assert.equal(amountPill.children[0],'400');
 await click('Original'); assert.equal(saved.at(-1).data.batchScale,1);
 assert.ok(tree.root.findAllByType('button').some(b=>b.props.title==='Edit original recipe quantity'));
 act(() => tree.unmount());
 let offline = true;
 act(() => { tree = TestRenderer.create(React.createElement(RecipePage, { dish, ingredients, dishIngs:links, onSave:async(id,data)=>{ if(offline) throw new Error('offline'); saved.push({id,data}); }, notify:()=>{}, onBack:()=>{} })); });
 await click('Double');
 assert.ok(tree.root.findAllByProps({role:'alert'}).some(n=>n.children.join('').includes('Batch preview is not saved')));
 assert.equal(input('Batch multiplier').props.value,'2');
 offline = false;
 await click('Apply batch');
 assert.equal(saved.at(-1).data.batchScale,2);
 assert.equal(tree.root.findAllByProps({role:'alert'}).length,0);
 console.log('Scaling component checks passed: presets, invalid input, ingredient target, servings, save failure/retry, scaled cook defaults and payload, blocked overdraw, preserved original links, scaled recipe display, reset to original.');
} catch(error) { console.error(error); process.exitCode=1; }
finally { if(tree) act(()=>tree.unmount()); await server.close(); }
