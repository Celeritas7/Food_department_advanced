import React from 'react';
import TestRenderer, { act } from 'react-test-renderer';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
const server=await createServer({server:{middlewareMode:true},appType:'custom'});
const {default:IngredientForm}=await server.ssrLoadModule('/src/components/forms/IngredientForm.jsx');
const {default:IngredientsPage}=await server.ssrLoadModule('/src/components/pages/IngredientsPage.jsx');
const {default:DishForm}=await server.ssrLoadModule('/src/components/forms/DishForm.jsx');
const {default:Substitution}=await server.ssrLoadModule('/src/components/forms/RecipeSubstitutionControl.jsx');
const {default:RecipePage}=await server.ssrLoadModule('/src/components/pages/RecipePage.jsx');
const fish={id:'f',name:'Fish sauce',aliases:['nước mắm','ナンプラー'],unit:'ml',stock_qty:50};
const soy={id:'s',name:'Soy sauce',aliases:['Shoyu'],unit:'ml',stock_qty:100};
const salt={id:'a',name:'Salt',unit:'g',stock_qty:200};
const ingredients=[fish,soy,salt];
const links=[{dish_id:'d',ingredient_id:'f',qty:10,recipe_unit:'ml'},{dish_id:'d',ingredient_id:'a',qty:5,recipe_unit:'g'}];
const dish={id:'d',name:'Kimchi',status:'In Progress',recipe_data:{batchScale:0.5,ingredientGroups:[{id:'g',name:'Main',items:[{id:'i',text:'Fish sauce',ingredientId:'f'}]}],preparation:[],cookingSteps:[]}};
let tree;
const find=label=>tree.root.findByProps({'aria-label':label});
const change=(label,value)=>act(()=>find(label).props.onChange({target:{value}}));
const text=()=>JSON.stringify(tree.toJSON());
const button=name=>tree.root.findAllByType('button').find(b=>b.children.join('').trim()===name);
const click=async name=>{const b=button(name);assert.ok(b,'Missing '+name);await act(async()=>{await b.props.onClick();});};
try {
 const saved=[];
 act(()=>{tree=TestRenderer.create(React.createElement(IngredientForm,{initial:fish,onSave:data=>saved.push(data),onCancel:()=>{}}));});
 change('Ingredient alternate names','nước mắm, NUOC MAM\nナンプラー');
 act(()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}}));
 assert.deepEqual(saved[0].aliases,['nước mắm','ナンプラー']);
 change('Ingredient alternate names','x'.repeat(121));
 act(()=>tree.root.findByType('form').props.onSubmit({preventDefault(){}}));
 assert.equal(saved.length,1);assert.ok(tree.root.findByProps({role:'alert'}));
 act(()=>tree.unmount());
 act(()=>{tree=TestRenderer.create(React.createElement(IngredientsPage,{ingredients,onEdit:()=>{},onBuy:()=>{}}));});
 act(()=>tree.root.findByProps({placeholder:'Search ingredients...'}).props.onChange({target:{value:'nuoc mam'}}));
 assert.match(text(),/Fish sauce/);assert.doesNotMatch(text(),/Soy sauce/);
 act(()=>tree.unmount());
 act(()=>{tree=TestRenderer.create(React.createElement(DishForm,{ingredients:[fish,{...soy,aliases:['nước mắm']}],intermediates:[],onSave:()=>{},onCancel:()=>{},onCreateIngredient:()=>{throw Error('Must not create ambiguous name');}}));});
 await click('📋 Paste');
 act(()=>tree.root.findAllByType('textarea').find(n=>n.props.placeholder?.startsWith('Paste your ingredient')).props.onChange({target:{value:'name,qty,unit\nnuoc mam,10,ml'}}));
 await click('Match');
 assert.match(text(),/Several pantry items share this name/);
 assert.equal(button('+ Create').props.disabled,true);
 act(()=>tree.unmount());
 const applied=[];
 act(()=>{tree=TestRenderer.create(React.createElement(Substitution,{dish,links,ingredients,onApply:async data=>applied.push(data)}));});
 change('Original recipe ingredient','f');
 const options=find('Replacement ingredient').findAllByType('option').map(n=>n.props.value);
 assert.ok(options.includes('s'));assert.ok(!options.includes('a'));assert.ok(!options.includes('f'));
 change('Search replacement ingredients','shoyu');change('Replacement ingredient','s');
 assert.equal(find('Replacement quantity').props.value,'');
 change('Replacement quantity','30');
 assert.equal(button('Use replacement').props.disabled,true);
 act(()=>find('Confirm recipe substitution').props.onChange({target:{checked:true}}));
 assert.equal(button('Use replacement').props.disabled,false);
 assert.match(text(),/15/);
 change('Replacement quantity','40');
 assert.equal(find('Confirm recipe substitution').props.checked,false);
 act(()=>find('Confirm recipe substitution').props.onChange({target:{checked:true}}));
 await click('Use replacement');
 assert.deepEqual(applied[0],{originalId:'f',replacementId:'s',qty:40,unit:'ml',note:''});
 assert.equal(ingredients[1].stock_qty,100);
 act(()=>tree.unmount());
 act(()=>{tree=TestRenderer.create(React.createElement(Substitution,{dish,links,ingredients,onApply:async()=>{throw Error('Substitution not saved');}}));});
 change('Original recipe ingredient','f');change('Replacement ingredient','s');change('Replacement quantity','30');
 act(()=>find('Confirm recipe substitution').props.onChange({target:{checked:true}}));
 await click('Use replacement');assert.match(text(),/Substitution not saved/);
 assert.equal(find('Replacement quantity').props.value,'30');
 act(()=>tree.unmount());
 // Whole-page integration flushes recipe saves before the atomic replacement.
 const events=[];
 act(()=>{tree=TestRenderer.create(React.createElement(RecipePage,{dish,ingredients,dishIngs:links,onSave:async()=>events.push('save'),onSubstitute:async data=>{events.push('replace');return{dish:{...dish,recipe_data:{...dish.recipe_data,ingredientGroups:[{id:'g',name:'Main',items:[{id:'i',text:'Fish sauce',ingredientId:'s'}]}],substitutionHistory:[{originalName:'Fish sauce',originalQty:10,originalUnit:'ml',replacementName:'Soy sauce',qty:data.qty,unit:data.unit}]}}};},notify:()=>{},onBack:()=>{}}));});
 change('Original recipe ingredient','f');change('Replacement ingredient','s');change('Replacement quantity','30');
 act(()=>find('Confirm recipe substitution').props.onChange({target:{checked:true}}));
 await click('Use replacement');
 assert.deepEqual(events,['save','replace']);assert.match(text(),/Using: /);assert.match(text(),/Soy sauce/);
 console.log('Identity component checks passed: alias editing/search, ambiguous CSV matching, duplicate exclusion, blank replacement amount, confirmation reset, batch preview, explicit payload, failed-save retention, recipe-save ordering and replacement display/history.');
} catch(error) {console.error(error);process.exitCode=1;}
finally {if(tree)act(()=>tree.unmount());await server.close();}
